# PPO + IterThink v7 (HL-Gauss critic). Branched from iterthink_v6.
#
# v6 is the v6 architecture verbatim: K=3 DenseNet-concat trunk, bounded convex
# residual gate, parallel dense + soft-MoE(16), affine-free RMSNorm. The ONLY
# change here is the CRITIC's value learning:
#
#   Scalar MSE regression  ->  HL-Gauss distributional classification.
#
# Motivation ("Stop Regressing", Farebrother et al. 2024): training the value
# function as a classification over a fixed value-support (cross-entropy against
# a Gaussian-smoothed target distribution) is better-conditioned than MSE
# regression and scales better with network capacity. Our trunk is deliberately
# high-capacity (densenet + 16-expert MoE), exactly the regime where the paper
# reports the largest classification-over-regression gains, and the better-
# behaved value gradients may also calm the policy (a sharper critic gives
# cleaner advantages, reducing the coherent Δμ drift that inflates our KL).
#
# Mechanics (cleanrl-idiomatic, via cleanrl.shared.hl_gauss.HLGaussSupport):
#   - critic head emits `num_bins` logits over support [v_min, v_max].
#   - scalar value (for GAE / bootstrap) = E[z] = sum(softmax(logits) * support).
#   - value loss = cross-entropy(softmax(logits), HL-Gauss(returns)). The
#     Gaussian projection (sigma = sigma_ratio * bin_width) smears each scalar
#     return target across neighbouring bins. PPO value clipping is dropped (it
#     has no meaning for a categorical head); vf_coef still scales the CE term.
#
# Support range: HalfCheetah uses NormalizeReward, so GAE returns are roughly
# standardized (measured std ~0.3-0.7). [-20, 20] with 255 bins keeps the active
# region finely resolved (bin_width ~0.16) while leaving generous headroom for
# transient return tails; clamp_targets guards the rare excursion. These are the
# proven defaults from ppo_continuous_action_pmpo_d4_hlgauss_v2 on this env.
#
# Unchanged: full v6 trunk/actor, PPO config, 10 update epochs.
