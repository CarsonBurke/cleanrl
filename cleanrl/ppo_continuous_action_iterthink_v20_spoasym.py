# PPO + IterThink v20 (SPO-asym objective on the tanh_gae winner). From v19.
#
# WHY v20. The v19 attribution settled that the +15-19% over the v10 baseline comes
# from BOUNDED/outlier-robust advantage shaping (tanh_gae = tanh(zscore(GAE)/kappa)),
# NOT the distributional critic — and that the win needed a TRUST REGION (PPO clip +
# target_kl). raw GAE + KL cap alone was the WORST arm; the cap is only an enabler
# once the advantage is bounded. v20 keeps the winning advantage and swaps the trust
# region itself: PPO's hard ratio-clip + KL early-stop  ->  SPO's smooth asymmetric
# quadratic penalty (Simple Policy Optimization, as used across this repo's spo_asym
# variants). SPO is a COMPLETE clip replacement, so it also subsumes the KL cap.
#
#   J(θ) = E[ r·A~  −  (|A~|/(2·ε(A~,r))) · (r−1)² ]
#   ε(A~,r) = spo_eps_high   if sign(A~) == sign(r−1)   (drift agrees with advantage)
#             spo_eps_low    otherwise                  (drift opposes advantage)
#
# Strength = ε bounds. Smaller ε => larger penalty coeff |A~|/(2ε) => TIGHTER trust
# region. Default = FULL strength (baseline 0.20/0.28). Half-strength (0.40/0.56)
# doubles ε, halving the penalty — that was too weak (permitted too much drift). The
# penalty is a soft, |A~|-scaled, asymmetric trust region: it grows quadratically in
# (r−1), is looser in the helpful direction (ε_high), and tighter against it (ε_low).
#
# adv_transform default stays "tanh_gae" (the v19 winner). The mean-value GAE and the
# distributional λ-return value target (v10) are UNCHANGED; only the policy OBJECTIVE
# changes. target_kl defaults OFF (SPO is the trust region); KL is logged to watch drift.
